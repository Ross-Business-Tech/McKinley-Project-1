"""Store for demo session turns and eval outcomes.

Local development and tests use a SQLite file (gitignored). A shared deployment can set DATABASE_URL to a Postgres
database (for example Supabase) and the same queries run there. Queries are written once with `?` placeholders and
translated for Postgres.
"""

import hashlib
import json
import sqlite3
import threading
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

SCHEMA = """
CREATE TABLE IF NOT EXISTS chat_turns (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  session_id TEXT NOT NULL,
  mode TEXT NOT NULL,
  persona_id TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('user','assistant')),
  content TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_turns_session ON chat_turns(session_id, mode, persona_id, id);
-- Gate decisions: safe routing metadata only (no message text, no context values).
CREATE TABLE IF NOT EXISTS gate_decisions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  session_id TEXT NOT NULL,
  mode TEXT NOT NULL,
  persona_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  data TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_gate_session ON gate_decisions(session_id, mode, persona_id, id);
-- In-progress customer action drafts (one per session + persona). Values are redacted message slots only.
CREATE TABLE IF NOT EXISTS action_drafts (
  session_id TEXT NOT NULL,
  persona_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  data TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (session_id, persona_id)
);
-- PROTOTYPE system of record (stands in for Yardi work orders / CRM tour requests / staff queue). Nobody is
-- notified and nothing leaves this database.
CREATE TABLE IF NOT EXISTS prototype_records (
  seq INTEGER PRIMARY KEY AUTOINCREMENT,
  id TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL,
  session_hash TEXT NOT NULL,
  persona_id TEXT,
  created_at TEXT NOT NULL,
  data TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_records_persona ON prototype_records(persona_id, kind, seq);
CREATE TABLE IF NOT EXISTS eval_runs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  created_at TEXT NOT NULL,
  targets TEXT NOT NULL,
  aware_prompt_version TEXT NOT NULL,
  baseline_prompt_version TEXT NOT NULL,
  temperature REAL
);
CREATE TABLE IF NOT EXISTS eval_results (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  run_id INTEGER NOT NULL REFERENCES eval_runs(id),
  case_id TEXT NOT NULL,
  mode TEXT NOT NULL,
  created_at TEXT NOT NULL,
  data TEXT NOT NULL,
  human_verdict TEXT,
  human_notes TEXT
);
"""

MAX_HISTORY_TURNS = 6


def now_iso() -> str:
    return datetime.now(UTC).isoformat()


def session_hash(session_id: str) -> str:
    """One-way short id shown to staff and stored on records; the raw session id is never exposed."""
    return hashlib.sha256(session_id.encode()).hexdigest()[:10]


_TABLES = ("chat_turns", "gate_decisions", "action_drafts", "prototype_records", "eval_runs", "eval_results")


def _postgres_schema() -> str:
    """The same tables for Postgres. Row-level security is switched on with no policies, so Supabase's public Data
    API (the anon key) can read nothing; the backend connects as the database owner, which bypasses it."""
    ddl = (SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
           .replace("temperature REAL", "temperature DOUBLE PRECISION"))
    rls = "".join(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;\n" for t in _TABLES)
    return ddl + rls


class Store:
    def __init__(self, path: Path | None = None, database_url: str | None = None):
        self._lock = threading.Lock()
        self._in_tx = False
        self._pg_url = database_url or None
        self.dialect = "postgres" if self._pg_url else "sqlite"
        # `IS` compares to NULL in SQLite; Postgres needs IS NOT DISTINCT FROM.
        self._same = "IS NOT DISTINCT FROM" if self._pg_url else "IS"
        if self._pg_url:
            self._conn: Any = self._connect_pg()
            with self._lock:
                self._conn.execute(_postgres_schema())
        else:
            if path is None:
                raise ValueError("Store needs a SQLite path or a database_url")
            path.parent.mkdir(parents=True, exist_ok=True)
            self._conn = sqlite3.connect(path, check_same_thread=False)
            self._conn.row_factory = sqlite3.Row
            with self._lock:
                self._conn.executescript(SCHEMA)

    # ---- connection plumbing ----
    def _connect_pg(self) -> Any:
        import psycopg  # imported here so a SQLite-only run never needs it
        from psycopg.rows import dict_row
        # prepare_threshold=None keeps this working behind Supabase's transaction pooler (port 6543).
        return psycopg.connect(self._pg_url, autocommit=True, row_factory=dict_row, prepare_threshold=None,
                               connect_timeout=10, keepalives=1, keepalives_idle=30, keepalives_interval=10,
                               keepalives_count=3)

    def _ensure(self) -> None:
        """Reconnect if the Postgres connection was dropped (idle timeout, pooler restart, free-tier sleep)."""
        if self._pg_url and (self._conn.closed or self._conn.broken):
            self._conn = self._connect_pg()

    def _sql(self, query: str) -> str:
        return query.replace("%", "%%").replace("?", "%s") if self._pg_url else query

    def _q(self, query: str, args: Any = ()) -> Any:
        """Run one statement and return the cursor. Reads retry once on a dropped Postgres connection."""
        self._ensure()
        sql = self._sql(query)
        if not self._pg_url:
            return self._conn.execute(sql, args)
        import psycopg
        try:
            return self._conn.execute(sql, args)
        except (psycopg.OperationalError, psycopg.InterfaceError):
            if self._in_tx:
                raise
            self._conn = self._connect_pg()
            return self._conn.execute(sql, args)

    def _qmany(self, query: str, rows: list[tuple[Any, ...]]) -> None:
        self._ensure()
        cur = self._conn.cursor()
        cur.executemany(self._sql(query), rows)

    @contextmanager
    def _tx(self) -> Iterator[None]:
        """One transaction: commit on success, roll back on error (callers already hold self._lock)."""
        self._ensure()
        self._in_tx = True
        try:
            if self._pg_url:
                with self._conn.transaction():
                    yield
            else:
                with self._conn:
                    yield
        finally:
            self._in_tx = False

    # ---- chat sessions ----
    def user_messages(self, session_id: str, persona_id: str) -> list[str]:
        """Everything this person typed in this session (any mode, no cap): for session-wide rules such as
        'I'm not the account holder', which must not expire when the chat history window moves on."""
        with self._lock:
            rows = self._q(
                "SELECT content FROM chat_turns WHERE session_id=? AND persona_id=? AND role='user' ORDER BY id",
                (session_id, persona_id)).fetchall()
        return [r["content"] for r in rows]

    def history(self, session_id: str, mode: str, persona_id: str) -> list[dict[str, str]]:
        with self._lock:
            rows = self._q(
                "SELECT role, content FROM chat_turns WHERE session_id=? AND mode=? AND persona_id=? "
                "ORDER BY id DESC LIMIT ?",
                (session_id, mode, persona_id, MAX_HISTORY_TURNS * 2),
            ).fetchall()
        msgs = [{"role": r["role"], "content": r["content"]} for r in reversed(rows)]
        while msgs and msgs[0]["role"] != "user":  # API requires history to start with a user turn
            msgs.pop(0)
        return msgs

    def append_turns(self, session_id: str, mode: str, persona_id: str, user: str, assistant: str) -> None:
        ts = now_iso()
        with self._lock, self._tx():
            self._qmany(
                "INSERT INTO chat_turns(session_id, mode, persona_id, role, content, created_at) "
                "VALUES (?,?,?,?,?,?)",
                [(session_id, mode, persona_id, "user", user, ts),
                 (session_id, mode, persona_id, "assistant", assistant, ts)],
            )

    def conversations(self, limit: int = 30) -> list[dict[str, Any]]:
        """STAFF view: recent aware-mode conversations, keyed by a one-way session hash (never the session id)."""
        with self._lock:
            rows = self._q(
                "SELECT session_id, persona_id, COUNT(*) AS n, MIN(created_at) AS started, MAX(created_at) AS last "
                "FROM chat_turns WHERE mode LIKE 'aware|%' GROUP BY session_id, persona_id "
                "ORDER BY MAX(id) DESC LIMIT ?",
                (limit,)).fetchall()
            flags: dict[str, list[str]] = {}
            for r in rows:  # what needs a person, from the gate log (no message text)
                got: list[str] = []
                for g in self._q("SELECT data FROM gate_decisions WHERE session_id=? AND mode LIKE "
                                            "'aware|%'", (r["session_id"],)).fetchall():
                    d = json.loads(g["data"])
                    if d.get("safety_response") == "full_alert" or d.get("urgency") == "emergency":
                        got.append("urgent")
                    elif d.get("safety_rule") in ("R3", "R4", "R6", "R9") or d.get("safety_response") == "care_line":
                        got.append("wellbeing")
                    if d.get("workflow") == "human_handoff" or "human_requested" in d.get("risk_flags", []):
                        got.append("asked_for_person")
                    if d.get("safety_semantic") in ("timeout", "error", "bad_output", "rate_limited"):
                        got.append("safety_check_failed")
                flags[r["session_id"]] = list(dict.fromkeys(got))
        order = {"urgent": 0, "wellbeing": 1, "asked_for_person": 2, "safety_check_failed": 3}
        return [{"session_hash": session_hash(r["session_id"]),
                 "persona_id": r["persona_id"] if r["persona_id"] not in ("", "none") else None,
                 "messages": r["n"] // 2, "started": r["started"], "last": r["last"],
                 "needs_action": sorted(flags.get(r["session_id"], []), key=lambda f: order.get(f, 9))} for r in rows]

    def conversation(self, wanted: str, limit: int = 200) -> list[dict[str, str]]:
        """Turns of the conversation whose session_hash is `wanted`."""
        with self._lock:
            ids = [r["session_id"] for r in self._q(
                "SELECT DISTINCT session_id FROM chat_turns WHERE mode LIKE 'aware|%'").fetchall()]
            sid = next((i for i in ids if session_hash(i) == wanted), None)
            if sid is None:
                return []
            rows = self._q(
                "SELECT role, content, persona_id, created_at FROM chat_turns "
                "WHERE session_id=? AND mode LIKE 'aware|%' "
                "ORDER BY id LIMIT ?", (sid, limit)).fetchall()
        return [dict(r) for r in rows]

    # ---- gate decision log ----
    def log_gate(self, session_id: str, mode: str, persona_id: str, data: dict[str, Any]) -> None:
        with self._lock, self._tx():
            self._q(
                "INSERT INTO gate_decisions(session_id, mode, persona_id, created_at, data) VALUES (?,?,?,?,?)",
                (session_id, mode, persona_id, now_iso(), json.dumps(data)),
            )

    def last_gate(self, session_id: str, mode: str, persona_id: str) -> dict[str, Any] | None:
        with self._lock:
            row = self._q(
                "SELECT data FROM gate_decisions WHERE session_id=? AND mode=? AND persona_id=? "
                "ORDER BY id DESC LIMIT 1", (session_id, mode, persona_id),
            ).fetchone()
        return json.loads(row["data"]) if row else None

    def gate_log(self, limit: int = 50) -> list[dict[str, Any]]:
        with self._lock:
            rows = self._q(
                "SELECT * FROM gate_decisions ORDER BY id DESC LIMIT ?", (limit,)).fetchall()
        # Session ids are bearer-like (they key chat history), so only a short one-way hash is exposed.
        return [{"id": r["id"], "session": session_hash(r["session_id"]),
                 "mode": r["mode"], "persona_id": r["persona_id"],
                 "created_at": r["created_at"], **json.loads(r["data"])} for r in rows]

    # ---- customer action drafts ----
    def get_draft(self, session_id: str, persona_id: str, include_declined: bool = False) -> dict[str, Any] | None:
        """The open draft. A declined draft (kept only so "send it after all" can restore it) is hidden unless
        include_declined: it can't be confirmed, cancelled or shown."""
        with self._lock:
            row = self._q("SELECT kind, data FROM action_drafts WHERE session_id=? AND persona_id=?",
                                     (session_id, persona_id)).fetchone()
        d = {"kind": row["kind"], **json.loads(row["data"])} if row else None
        return d if d and (include_declined or not d.get("declined")) else None

    def save_draft(self, session_id: str, persona_id: str, kind: str, data: dict[str, Any]) -> None:
        with self._lock, self._tx():
            self._q(
                "INSERT INTO action_drafts(session_id, persona_id, kind, data, updated_at) VALUES (?,?,?,?,?) "
                "ON CONFLICT(session_id, persona_id) DO UPDATE SET kind=excluded.kind, data=excluded.data, "
                "updated_at=excluded.updated_at", (session_id, persona_id, kind, json.dumps(data), now_iso()))

    def take_draft(self, session_id: str, persona_id: str, kind: str) -> dict[str, Any] | None:
        """Atomically remove and return the draft, so concurrent confirms can write at most one record."""
        with self._lock, self._tx():
            row = self._q(
                "DELETE FROM action_drafts WHERE session_id=? AND persona_id=? AND kind=? RETURNING kind, data",
                (session_id, persona_id, kind)).fetchone()
        return {"kind": row["kind"], **json.loads(row["data"])} if row else None

    def mark_stale(self, session_id: str, persona_id: str, kind: str, data: dict[str, Any]) -> None:
        """Update only; never re-inserts a draft that a concurrent confirm already took."""
        with self._lock, self._tx():
            self._q("UPDATE action_drafts SET data=? WHERE session_id=? AND persona_id=? AND kind=?",
                               (json.dumps(data), session_id, persona_id, kind))

    def clear_draft(self, session_id: str, persona_id: str) -> None:
        with self._lock, self._tx():
            self._q("DELETE FROM action_drafts WHERE session_id=? AND persona_id=?",
                               (session_id, persona_id))

    # ---- synthetic reference data (tables from migration 0002; see app/seed_synthetic.py) ----
    def has_reference_tables(self) -> bool:
        """True when migration 0002 has been applied (the app never creates these tables itself)."""
        try:
            with self._lock:
                self._q("SELECT COUNT(*) AS n FROM residents").fetchone()
            return True
        except Exception:
            if self._pg_url:  # a failed statement must not leave the connection unusable
                self._conn = self._connect_pg()
            return False

    def replace_reference(self, communities: list[tuple[str, str]], residents: list[dict[str, Any]],
                          interactions: list[dict[str, Any]], meta: dict[str, str]) -> None:
        """Replace all synthetic reference rows in one transaction (a reload never leaves a half-loaded set)."""
        with self._lock, self._tx():
            for table in ("interactions", "residents", "communities", "dataset_meta"):
                self._q(f"DELETE FROM {table}")
            self._qmany("INSERT INTO communities(name, region, synthetic) VALUES (?,?,?)",
                        [(n, r, True) for n, r in communities])
            self._qmany("INSERT INTO residents(resident_id, community, first_name, preferred_language, data, "
                        "synthetic) VALUES (?,?,?,?,?,?)",
                        [(r["resident_id"], r.get("community") or None, r.get("first_name", ""),
                          r.get("preferred_language", ""), json.dumps(r), True) for r in residents])
            self._qmany('INSERT INTO interactions(interaction_id, resident_id, "timestamp", channel, category, '
                        "subject, full_text, status, resolved_date, follow_up_needed, synthetic) "
                        "VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                        [(i["interaction_id"], i["resident_id"], i.get("timestamp", ""), i.get("channel", ""),
                          i.get("category", ""), i.get("subject", ""), i.get("full_text", ""), i.get("status", ""),
                          i.get("resolved_date", ""), bool(i.get("follow_up_needed")), True) for i in interactions])
            self._qmany("INSERT INTO dataset_meta(key, value) VALUES (?,?)", list(meta.items()))

    def reference_rows(self) -> tuple[list[dict[str, str]], list[dict[str, str]], dict[str, str]] | None:
        """(resident rows, interaction rows, meta) as the workbook loader expects them, or None if not loaded."""
        if not self.has_reference_tables():
            return None
        with self._lock:
            res = [json.loads(r["data"]) for r in self._q("SELECT data FROM residents ORDER BY resident_id")]
            inter = [dict(r) for r in self._q(
                'SELECT interaction_id, resident_id, "timestamp" AS timestamp, channel, category, subject, '
                "full_text, status, resolved_date, follow_up_needed FROM interactions ORDER BY interaction_id")]
            meta = {r["key"]: r["value"] for r in self._q("SELECT key, value FROM dataset_meta")}
        if not res:
            return None
        for i in inter:
            i["follow_up_needed"] = "Y" if i["follow_up_needed"] in (1, True, "1", "Y") else "N"
            i.update({k: ("" if v is None else str(v)) for k, v in i.items() if k != "follow_up_needed"})
        return [{k: str(v) for k, v in r.items()} for r in res], inter, meta

    # ---- prototype records ----
    def add_record(self, prefix: str, kind: str, session_id: str, persona_id: str | None,
                   data: dict[str, Any]) -> dict[str, Any]:
        """Write a prototype record and return it with its generated id. Raises on any DB error."""
        shash = session_hash(session_id)
        created = now_iso()
        with self._lock, self._tx():
            seq = (self._q("SELECT COALESCE(MAX(seq), 0) AS m FROM prototype_records").fetchone()["m"]
                   + 1)
            rid = f"{prefix}-{1000 + seq}"
            self._q(
                "INSERT INTO prototype_records(seq, id, kind, session_hash, persona_id, created_at, data) "
                "VALUES (?,?,?,?,?,?,?)", (seq, rid, kind, shash, persona_id, created, json.dumps(data)))
        return {**data, "id": rid, "kind": kind, "session_hash": shash, "persona_id": persona_id,
                "created_at": created}

    def add_record_once(self, prefix: str, kind: str, session_id: str, persona_id: str | None,
                        data: dict[str, Any], once_key: str) -> dict[str, Any]:
        """Insert unless a record with the same (session, persona, once_key) exists; check and insert under one lock."""
        shash = session_hash(session_id)
        with self._lock, self._tx():
            for r in self._q(f"SELECT * FROM prototype_records WHERE session_hash=? AND kind=? AND "
                                        f"persona_id {self._same} ?", (shash, kind, persona_id)).fetchall():
                d = json.loads(r["data"])
                if d.get("once_key") == once_key:
                    return {**d, "id": r["id"], "kind": r["kind"], "session_hash": r["session_hash"],
                            "persona_id": r["persona_id"], "created_at": r["created_at"], "_existing": True}
            seq = self._q("SELECT COALESCE(MAX(seq), 0) AS m FROM prototype_records").fetchone()["m"] + 1
            rid, created = f"{prefix}-{1000 + seq}", now_iso()
            payload = {**data, "once_key": once_key}
            self._q(
                "INSERT INTO prototype_records(seq, id, kind, session_hash, persona_id, created_at, data) "
                "VALUES (?,?,?,?,?,?,?)", (seq, rid, kind, shash, persona_id, created, json.dumps(payload)))
        return {**payload, "id": rid, "kind": kind, "session_hash": shash, "persona_id": persona_id,
                "created_at": created}

    def records(self, persona_id: str | None = None, kind: str | None = None,
                session_id: str | None = None, limit: int = 100) -> list[dict[str, Any]]:
        sql, args = "SELECT * FROM prototype_records WHERE 1=1", []
        if persona_id is not None:
            sql += " AND persona_id=?"
            args.append(persona_id)
        if kind is not None:
            sql += " AND kind=?"
            args.append(kind)
        if session_id is not None:
            sql += " AND session_hash=?"
            args.append(session_hash(session_id))
        sql += " ORDER BY seq DESC LIMIT ?"
        args.append(limit)
        with self._lock:
            rows = self._q(sql, args).fetchall()
        return [{**json.loads(r["data"]), "id": r["id"], "kind": r["kind"], "session_hash": r["session_hash"],
                 "persona_id": r["persona_id"], "created_at": r["created_at"]} for r in rows]

    # ---- evals ----
    def create_run(self, targets: list[str], aware_v: str, baseline_v: str, temperature: float | None) -> int:
        with self._lock, self._tx():
            cur = self._q(
                "INSERT INTO eval_runs(created_at, targets, aware_prompt_version, baseline_prompt_version, "
                "temperature) VALUES (?,?,?,?,?) RETURNING id",
                (now_iso(), json.dumps(targets), aware_v, baseline_v, temperature),
            )
            return int(cur.fetchone()["id"])

    def runs(self, limit: int = 20) -> list[dict[str, Any]]:
        with self._lock:
            rows = self._q("SELECT * FROM eval_runs ORDER BY id DESC LIMIT ?", (limit,)).fetchall()
        return [{**dict(r), "targets": json.loads(r["targets"])} for r in rows]

    def add_result(self, run_id: int, case_id: str, mode: str, data: dict[str, Any]) -> int:
        with self._lock, self._tx():
            cur = self._q(
                "INSERT INTO eval_results(run_id, case_id, mode, created_at, data) VALUES (?,?,?,?,?) RETURNING id",
                (run_id, case_id, mode, data["created_at"], json.dumps(data)),
            )
            return int(cur.fetchone()["id"])

    def latest_run_id(self) -> int | None:
        with self._lock:
            row = self._q("SELECT MAX(id) AS id FROM eval_runs").fetchone()
        return row["id"] if row and row["id"] is not None else None

    def results(self, run_id: int) -> list[dict[str, Any]]:
        with self._lock:
            rows = self._q(
                "SELECT * FROM eval_results WHERE run_id=? ORDER BY id", (run_id,)
            ).fetchall()
        return [self._row(r) for r in rows]

    def get_result(self, result_id: int) -> dict[str, Any] | None:
        with self._lock:
            r = self._q("SELECT * FROM eval_results WHERE id=?", (result_id,)).fetchone()
        return self._row(r) if r else None

    def update_result_data(self, result_id: int, data: dict[str, Any]) -> None:
        with self._lock, self._tx():
            self._q("UPDATE eval_results SET data=? WHERE id=?", (json.dumps(data), result_id))

    def review(self, result_id: int, verdict: str | None, notes: str | None) -> None:
        with self._lock, self._tx():
            self._q(
                "UPDATE eval_results SET human_verdict=?, human_notes=? WHERE id=?", (verdict, notes, result_id)
            )

    @staticmethod
    def _row(r: Any) -> dict[str, Any]:
        data = json.loads(r["data"])
        data.update(id=r["id"], run_id=r["run_id"], case_id=r["case_id"], mode=r["mode"],
                    human_verdict=r["human_verdict"], human_notes=r["human_notes"])
        return data
